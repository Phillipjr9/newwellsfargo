import test from "node:test";
import assert from "node:assert/strict";
import { createServer } from "node:http";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

test("customer invitations are single-use and recovery preserves the assigned workspace", async () => {
  const directory = mkdtempSync(join(tmpdir(), "customer-access-"));
  process.env.DEMO_DATA_DIR = directory;
  process.env.DEMO_ADMIN_TOKEN = "isolated-customer-access-test-admin";
  const { adminApi, demoApi } = await import("../server/api.mjs");
  const server = createServer((req, res) => adminApi(req, res, () => demoApi(req, res, () => { res.writeHead(404); res.end(); })));
  await new Promise(resolve => server.listen(0, "127.0.0.1", resolve));
  const base = `http://127.0.0.1:${server.address().port}`;
  const call = (path, { method = "GET", cookie, body, headers = {} } = {}) => fetch(`${base}/api/${path}`, {
    method, headers: { "Content-Type": "application/json", Origin: base, ...(cookie ? { Cookie: cookie } : {}), ...headers },
    body: body === undefined ? undefined : JSON.stringify(body),
  });
  const cookieFrom = response => response.headers.getSetCookie()[0].split(";")[0];
  const post = (path, body, cookie, headers) => call(path, { method: "POST", body, cookie, headers });
  const claim = code => post("demo/customer-access/claim", { code });
  const signIn = code => post("demo/customer-access/session", { code });
  try {
    const root = cookieFrom(await post("admin/session", { token: process.env.DEMO_ADMIN_TOKEN }));
    const created = await post("admin/customers", { name: "Returning Customer" }, root);
    assert.equal(created.status, 201);
    const { id } = (await created.json()).customer;
    const endpoint = `admin/customers/${id}/invitation`;
    const issue = status => post(endpoint, { status }, root);
    assert.equal((await call("demo/workspace", { headers: { "X-Demo-Workspace": id } })).status, 401);
    assert.equal((await post(endpoint, { status: "not_enrolled" })).status, 401);
    const { admin, accessCode: staffCode } = await (await post("admin/admins", { name: "Support", email: "staff@example.test", role: "limited" }, root)).json();
    await call(`admin/users/${id}/assign-admin`, { method: "PUT", body: { ownerAdminId: admin.id }, cookie: root });
    const staff = cookieFrom(await post("admin/staff/session", { email: admin.email, code: staffCode }));
    assert.equal((await post(endpoint, { status: "not_enrolled" }, staff)).status, 403);
    const first = await issue("not_enrolled");
    assert.equal(first.status, 201);
    const { code } = await first.json();
    assert.match(code, /^join-/);
    const backup = await (await call("admin/backup", { cookie: root })).text();
    assert.equal(backup.includes(code), false);
    assert.doesNotMatch(backup, /inviteHash|accessHash/);
    assert.equal((await post("demo/customer-access/claim", { code }, undefined, { Origin: "https://example.test" })).status, 403);
    const responses = await Promise.all([claim(code), claim(code)]);
    assert.deepEqual(responses.map(response => response.status).sort(), [200, 401]);
    const { accessCode } = await responses.find(response => response.ok).json();
    assert.equal((await signIn(code)).status, 401);
    const initial = await signIn(accessCode);
    assert.equal(initial.status, 200);
    assert.equal((await initial.json()).workspaceId, id);
    const session = cookieFrom(initial);
    assert.equal((await post("demo/action", { action: "preference", payload: { key: "hideBalances", value: true } }, session)).status, 200);
    const exit = await post("demo/exit", {}, session);
    assert.equal((await exit.json()).managed, true);
    assert.equal((await call("demo/workspace", { cookie: session, headers: { "X-Demo-Session": "required" } })).status, 401);
    const returned = cookieFrom(await signIn(accessCode));
    const workspace = await (await call("demo/workspace", { cookie: returned })).json();
    assert.equal(workspace.workspaceId, id);
    assert.equal(workspace.profile.name, "Returning Customer");
    assert.equal(workspace.state.preferences.hideBalances, true);
    assert.doesNotMatch(JSON.stringify(workspace), /inviteHash|accessHash/);
    const customer = `admin/customers/${id}`;
    const update = (body, cookie = root) => call(customer, { method: "PUT", body, cookie });
    assert.equal((await update({ name: "Unauthorized" }, staff)).status, 403);
    assert.equal((await update({ name: " " })).status, 400);
    assert.equal((await update({ email: "not-an-email" })).status, 400);
    assert.equal((await update({ name: "Updated Customer", email: "Contact@Example.Test" })).status, 200);
    const updated = await (await call("demo/workspace", { cookie: returned })).json();
    assert.deepEqual(updated.profile, { name: "Updated Customer", firstName: "Updated", initials: "UC", email: "contact@example.test" });
    assert.equal((await update({ email: "" })).status, 200);
    assert.equal((await (await call(`admin/workspaces/${id}`, { cookie: root })).json()).profile.email, "");
    assert.equal((await post(`${customer}/revoke-sessions`, {}, staff)).status, 403);
    assert.equal((await call(`${customer}/revoke-sessions`, { cookie: root })).status, 405);
    assert.equal((await post(`${customer}/revoke-sessions`, {}, root)).status, 200);
    assert.equal((await call("demo/workspace", { cookie: returned, headers: { "X-Demo-Session": "required" } })).status, 401);
    assert.equal((await signIn(accessCode)).status, 200);
    assert.equal((await post(`admin/customers/${id}/suspend`, { suspended: true }, root)).status, 200);
    assert.equal((await signIn(accessCode)).status, 401);
    assert.equal((await issue("enrolled")).status, 409);
    assert.equal((await post(`admin/customers/${id}/suspend`, { suspended: false }, root)).status, 200);
    const active = cookieFrom(await signIn(accessCode));
    const recovery = await issue("enrolled");
    assert.equal(recovery.status, 201);
    const replacement = await recovery.json();
    assert.equal((await signIn(accessCode)).status, 401);
    assert.equal((await call("demo/workspace", { cookie: active, headers: { "X-Demo-Session": "required" } })).status, 401);
    const file = join(directory, "customer-access", `${id}.json`);
    writeFileSync(file, JSON.stringify({ ...JSON.parse(readFileSync(file, "utf8")), expiresAt: 1 }));
    assert.equal((await claim(replacement.code)).status, 401);
    const refreshed = await (await issue("expired")).json();
    const newCode = (await (await claim(refreshed.code)).json()).accessCode;
    const recovered = cookieFrom(await signIn(newCode));
    assert.equal((await (await call("demo/workspace", { cookie: recovered })).json()).state.preferences.hideBalances, true);
    const exportAfter = await (await call("admin/backup", { cookie: root })).text();
    assert.doesNotMatch(exportAfter, /inviteHash|accessHash/);
    assert.equal(exportAfter.includes(newCode), false);
    const restore = await post("admin/restore", { ...JSON.parse(exportAfter), confirmation: "RESTORE" }, root);
    assert.equal(restore.status, 200);
    assert.equal((await signIn(newCode)).status, 401);
    assert.equal((await call("demo/workspace", { cookie: recovered, headers: { "X-Demo-Session": "required" } })).status, 401);
  } finally {
    await new Promise(resolve => server.close(resolve));
    rmSync(directory, { recursive: true, force: true });
  }
});
